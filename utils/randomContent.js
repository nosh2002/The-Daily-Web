const LAST_NAMES = ['כהן', 'לוי', 'מזרחי', 'פרץ', 'אברהם', 'ביטון', 'דהן', 'אזולאי', 'שפירא', 'גולן'];

function generatePersonName() {
  return `${choice(FIRST_NAMES)} ${choice(LAST_NAMES)}`;
}

