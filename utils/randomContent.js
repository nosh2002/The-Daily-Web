function randomInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function choice(arr) {
  return arr[randomInt(0, arr.length - 1)];
}

function generateTitle(category) {
  const topic = choice(TOPICS_BY_CATEGORY[category] || TOPICS_BY_CATEGORY['חדשות']);
  const place = choice(PLACES);
  const adjective = choice(ADJECTIVES);
  return `${topic} ${adjective} ב${place}`;
}

function generateSummary(title) {
  return `${title} - כל הפרטים, התגובות וההשלכות האפשריות, כפי שנחשפו הבוקר.`;
}

function generateParagraph() {
  const sentences = [
    choice(CONTEXT_SENTENCES),
    `${choice(REACTIONS)}.`,
    choice(CONTEXT_SENTENCES),
  ];
  return sentences.join(' ');
}

function generateBody(paragraphCount = 5) {
  const paragraphs = [];
  for (let i = 0; i < paragraphCount; i += 1) {
    paragraphs.push(generateParagraph());
  }
  paragraphs.push(choice(CLOSING_SENTENCES));
  return paragraphs.join('\n\n');
}

